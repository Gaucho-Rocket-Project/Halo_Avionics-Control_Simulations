"""Build and smoke-test native desktop executables with PyInstaller."""

from __future__ import annotations

import argparse
import ast
import hashlib
import importlib.metadata
import json
import platform
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path


APP_NAME = "SensorTelemetry"
SOURCE_DIR = Path(__file__).resolve().parent
TARGETS = {"Windows": "windows", "Darwin": "macos", "Linux": "linux"}


@dataclass(frozen=True)
class BuildPlan:
    target: str
    architecture: str
    mode: str
    entry: Path
    output_dir: Path
    work_dir: Path
    version: str

    @property
    def app_path(self) -> Path:
        name = APP_NAME
        if self.target == "macos":
            name += ".app"
        elif self.target == "windows" and self.mode == "onefile":
            name += ".exe"
        return self.output_dir / "app" / name

    @property
    def executable_path(self) -> Path:
        if self.target == "macos":
            return self.app_path / "Contents" / "MacOS" / APP_NAME
        if self.mode == "onedir":
            return self.app_path / (APP_NAME + (".exe" if self.target == "windows" else ""))
        return self.app_path


def create_build_plan(
    entry: Path,
    output_root: Path,
    target: str | None = None,
    mode: str = "onedir",
    version: str = "1.0.0",
    *,
    host_system: str | None = None,
    machine: str | None = None,
) -> BuildPlan:
    host = TARGETS.get(host_system or platform.system())
    if host is None:
        raise ValueError("Supported build hosts are Windows, macOS, and Linux.")
    target = target or host
    if target != host:
        raise ValueError(
            f"Cannot build {target} on {host}. PyInstaller is not a cross-compiler. "
            "Run on the target OS, or use the included GitHub Actions workflow."
        )
    if mode not in ("onedir", "onefile"):
        raise ValueError("Build mode must be 'onedir' or 'onefile'.")
    if host == "macos" and mode == "onefile":
        raise ValueError("macOS uses an .app bundle. Select --mode onedir for macOS.")
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError("Version must have three numeric parts, for example 1.0.0.")
    architecture = (machine or platform.machine()).lower()
    architecture = {"amd64": "x86_64", "aarch64": "arm64"}.get(architecture, architecture)
    if architecture not in ("x86_64", "arm64"):
        raise ValueError(f"Unsupported architecture: {architecture}. Use 64-bit x86 or ARM Python.")
    entry = entry.resolve()
    if not entry.is_file() or entry.suffix != ".py":
        raise ValueError(f"Python application entry point not found: {entry}")
    build_id = f"{target}-{architecture}-{mode}"
    return BuildPlan(
        target, architecture, mode, entry,
        output_root.resolve() / build_id,
        SOURCE_DIR / ".build" / build_id,
        version,
    )


def render_spec(
    plan: BuildPlan,
    calibration_file: Path | None = None,
    codesign_identity: str | None = None,
    extra_hiddenimports: Sequence[str] = (),
    extra_paths: Sequence[Path] = (),
) -> str:
    """Use an explicit TkAgg hook so unrelated GUI backends are not bundled."""
    datas = [(str(calibration_file), ".")] if calibration_file else []
    search_paths = [str(plan.entry.parent)] + [str(path) for path in extra_paths]
    hidden = [
        "matplotlib.backends.backend_tkagg",
        "matplotlib.backends.backend_agg",
        "matplotlib.backends.backend_pdf",
        "matplotlib.backends.backend_svg",
        "PIL._tkinter_finder",
        "PIL._imagingtk",
        *extra_hiddenimports,
    ]
    code = f'''# Generated by build_app.py. Rebuild via that script, not this file.
a = Analysis(
    [{str(plan.entry)!r}],
    pathex={search_paths!r},
    binaries=[],
    datas={datas!r},
    hiddenimports={hidden!r},
    hooksconfig={{'matplotlib': {{'backends': ['TkAgg']}}}},
    excludes=['PyQt5', 'PyQt6', 'PySide2', 'PySide6', 'IPython', 'pytest'],
    noarchive=False,
)
pyz = PYZ(a.pure)
'''
    signing = ""
    if plan.target == "macos":
        signing = f"    target_arch={plan.architecture!r},\n    codesign_identity={codesign_identity!r},\n"
    if plan.mode == "onefile":
        code += f'''exe = EXE(
    pyz, a.scripts, a.binaries, a.datas,
    name={APP_NAME!r},
    console=False,
    debug=False,
    strip=False,
    upx=False,
{signing})
'''
    else:
        code += f'''exe = EXE(
    pyz, a.scripts, [],
    exclude_binaries=True,
    name={APP_NAME!r},
    console=False,
    debug=False,
    strip=False,
    upx=False,
{signing})
collection = COLLECT(exe, a.binaries, a.datas, strip=False, upx=False, name={APP_NAME!r})
'''
    if plan.target == "macos":
        code += f'''app = BUNDLE(
    collection,
    name={APP_NAME + '.app'!r},
    bundle_identifier='org.sensortelemetry.desktop',
    info_plist={{
        'CFBundleShortVersionString': {plan.version!r},
        'CFBundleVersion': {plan.version!r},
        'NSHighResolutionCapable': True,
    }},
)
'''
    return code


def _replace_line_prefix(lines: List[str], lineno: int, old: str, new: str) -> bool:
    index = lineno - 1
    if 0 <= index < len(lines) and old in lines[index]:
        lines[index] = lines[index].replace(old, new, 1)
        return True
    return False


def _normalize_local_imports(text: str, package_name: str) -> Tuple[str, List[int], List[int]]:
    """Rewrite imports that depend on the source folder name into top-level imports.

    A repository folder such as ``Visualizer`` is a perfectly valid Python package
    name, so source files commonly contain ``from Visualizer.sensor_grapher import
    ...`` or a relative ``from .sensor_grapher import ...``. PyInstaller freezes the
    entry script as a top-level module, so those imports must be normalized or the
    finished executable fails with ``No module named 'Visualizer'``.
    """
    lines = text.splitlines(keepends=True)
    normalized: List[int] = []
    unresolved: List[int] = []
    prefix = f"{package_name}."

    try:
        tree = ast.parse(text)
    except SyntaxError:
        return text, [], []

    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom):
            if node.level > 0:
                target = node.module or ""
                if not target or "." in target:
                    unresolved.append(node.lineno)
                    continue
                old = "from " + "." * node.level + target
                if _replace_line_prefix(lines, node.lineno, old, f"from {target}"):
                    normalized.append(node.lineno)
                else:
                    unresolved.append(node.lineno)
            elif node.module and node.module.startswith(prefix):
                remainder = node.module[len(prefix):]
                if not remainder or "." in remainder:
                    unresolved.append(node.lineno)
                    continue
                if _replace_line_prefix(lines, node.lineno, f"from {node.module}", f"from {remainder}"):
                    normalized.append(node.lineno)
                else:
                    unresolved.append(node.lineno)
        elif isinstance(node, ast.Import):
            alias = node.names[0]
            if alias.asname and alias.name.startswith(prefix):
                remainder = alias.name[len(prefix):]
                if remainder and "." not in remainder and _replace_line_prefix(
                    lines, node.lineno, f"import {alias.name}", f"import {remainder} as {alias.asname}"
                ):
                    normalized.append(node.lineno)
                else:
                    unresolved.append(node.lineno)
            elif alias.name.startswith(prefix):
                unresolved.append(node.lineno)

    return "".join(lines), normalized, unresolved


def _local_module_names(tree: ast.AST, source_dir: Path) -> List[str]:
    """Return import names that resolve to sibling modules or packages on disk."""
    names: List[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            candidates = [alias.name.split(".")[0] for alias in node.names]
        elif isinstance(node, ast.ImportFrom):
            root = (node.module or "").split(".")[0] if node.module else ""
            candidates = [root] if root else []
        else:
            continue
        for name in candidates:
            if not name or name in names:
                continue
            if (source_dir / f"{name}.py").is_file() or (source_dir / name / "__init__.py").is_file():
                names.append(name)
    return names


@dataclass(frozen=True)
class AppSnapshot:
    """A clean, package-free copy of the application used as the PyInstaller entry."""

    entry: Path
    staging_dir: Path
    source_dir: Path
    source_package: str
    copied: Tuple[str, ...]
    normalized: Tuple[str, ...]
    unresolved: Tuple[str, ...]


def stage_app_snapshot(entry: Path, staging_dir: Path) -> AppSnapshot:
    """Copy the app into a neutral folder so imports never depend on a folder name.

    Sibling modules and local packages are copied alongside the entry script, and
    ``__init__.py`` is intentionally left behind so the snapshot is not a package.
    """
    source_dir = entry.parent
    package_name = source_dir.name
    if staging_dir.exists():
        shutil.rmtree(staging_dir)
    staging_dir.mkdir(parents=True)

    copied: List[str] = []
    normalized: List[str] = []
    unresolved: List[str] = []
    pending = [entry.resolve()]
    seen: set = set()

    while pending:
        source = pending.pop(0)
        if source in seen:
            continue
        seen.add(source)
        original = source.read_text(encoding="utf-8")
        rewritten, changed, missed = _normalize_local_imports(original, package_name)
        (staging_dir / source.name).write_text(rewritten, encoding="utf-8")
        copied.append(source.name)
        normalized.extend(f"{source.name}:{line}" for line in changed)
        unresolved.extend(f"{source.name}:{line}" for line in missed)

        for name in _local_module_names(ast.parse(original), source_dir):
            sibling = source_dir / f"{name}.py"
            if sibling.is_file():
                pending.append(sibling)
                continue
            package_init = source_dir / name / "__init__.py"
            if package_init.is_file() and not (staging_dir / name).exists():
                shutil.copytree(
                    source_dir / name, staging_dir / name, symlinks=True,
                    ignore=shutil.ignore_patterns("__pycache__", "*.py[cod]"),
                )

    return AppSnapshot(
        entry=staging_dir / entry.name,
        staging_dir=staging_dir,
        source_dir=source_dir,
        source_package=package_name,
        copied=tuple(copied),
        normalized=tuple(normalized),
        unresolved=tuple(unresolved),
    )


def check_dependencies() -> None:
    if sys.version_info < (3, 10):
        raise RuntimeError("Build with Python 3.10 or newer (3.12 is used in CI).")
    if sys.maxsize <= 2**32:
        raise RuntimeError("Use a 64-bit Python interpreter to build these desktop applications.")
    try:
        import tkinter
        import matplotlib.backends.backend_tkagg  # noqa: F401
        import PyInstaller  # noqa: F401

        tkinter.Tcl()
    except ImportError as exc:
        raise RuntimeError(
            "Build dependencies are missing. Run: python -m pip install -r requirements-build.txt. "
            "Tkinter must also be installed for this Python: python -m tkinter. "
            "On Debian/Ubuntu install python3-tk; on Fedora install python3-tkinter."
        ) from exc
    if platform.system() == "Linux":
        missing = [name for name in ("ldd", "objdump", "objcopy") if not shutil.which(name)]
        if missing:
            raise RuntimeError(f"Missing Linux build tools: {', '.join(missing)}. Install binutils and libc-bin.")


def stage_calibrations(source: Path | None, work_dir: Path) -> Path | None:
    if source is None:
        return None
    from sensor_grapher import calibrations_from_json, calibrations_to_json

    formulas = calibrations_from_json(source.read_text(encoding="utf-8"))
    destination = work_dir / "default_calibrations.json"
    destination.write_text(calibrations_to_json(formulas), encoding="utf-8")
    return destination


def smoke_test(plan: BuildPlan) -> None:
    if not plan.executable_path.is_file():
        raise RuntimeError(f"Built executable was not found: {plan.executable_path}")
    print("Testing the bundled Tcl/Tk window, calibrations, and PNG/PDF/SVG rendering...", flush=True)
    with tempfile.TemporaryDirectory(prefix="sensor-smoke-") as temp:
        report_path = Path(temp) / "report.json"
        result = subprocess.run(
            [str(plan.executable_path), "--smoke-test", "--smoke-report", str(report_path)],
            capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=120,
        )
        report = json.loads(report_path.read_text(encoding="utf-8")) if report_path.exists() else {}
        if result.returncode != 0 or report.get("status") != "passed":
            raise RuntimeError(
                "Bundled application smoke test failed. A desktop display is required; on headless Linux "
                "use xvfb-run -a python build_app.py.\n"
                + report.get("error", result.stderr or result.stdout or "No test report was written.")
            )
    print("Bundled application smoke test passed.", flush=True)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def create_release(plan: BuildPlan, *, tested: bool) -> Path:
    """Archive the entire runtime; tar preserves macOS symlinks and Unix executable bits."""
    release_dir = plan.output_dir / "releases"
    release_dir.mkdir(parents=True, exist_ok=True)
    basename = f"{APP_NAME}-{plan.version}-{plan.target}-{plan.architecture}-{plan.mode}"
    metadata = {
        "application": APP_NAME,
        "version": plan.version,
        "platform": plan.target,
        "architecture": plan.architecture,
        "mode": plan.mode,
        "built_at_utc": datetime.now(timezone.utc).isoformat(),
        "build_os": platform.platform(),
        "libc": list(platform.libc_ver()) if plan.target == "linux" else None,
        "python": platform.python_version(),
        "pyinstaller": importlib.metadata.version("pyinstaller"),
        "matplotlib": importlib.metadata.version("matplotlib"),
        "smoke_test": "passed" if tested else "skipped",
        "requires_python_installation": False,
        "signing": "Verify publisher signing separately before public distribution.",
    }
    with tempfile.TemporaryDirectory(prefix="sensor-release-", dir=plan.work_dir) as temp:
        stage = Path(temp) / APP_NAME
        stage.mkdir()
        destination = stage / plan.app_path.name
        if plan.app_path.is_dir():
            shutil.copytree(plan.app_path, destination, symlinks=True)
        else:
            shutil.copy2(plan.app_path, destination)
        if plan.target == "linux":
            binary = f"{APP_NAME}/{APP_NAME}" if plan.mode == "onedir" else APP_NAME
            launcher = stage / "launch.sh"
            launcher.write_text(
                '#!/bin/sh\nset -eu\nHERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)\n'
                f'exec "$HERE/{binary}" "$@"\n', encoding="utf-8",
            )
            launcher.chmod(0o755)
        instructions = {
            "windows": f"Extract this entire ZIP, then double-click {APP_NAME}.exe"
                + (f" inside the {APP_NAME} folder." if plan.mode == "onedir" else "."),
            "macos": f"Extract the archive and move {APP_NAME}.app to Applications, then open it.",
            "linux": "Extract the entire archive, then open launch.sh or run ./launch.sh in a terminal.",
        }
        (stage / "START_HERE.txt").write_text(
            instructions[plan.target]
            + "\nNo Python or pip installation is required. Keep all bundled files together.\n"
            + "Use File > Open Sensor CSV to load your data.\n"
            + "Match your OS and CPU architecture to this build. Linux requires compatible glibc and a desktop display.\n"
            + "Unsigned Windows/macOS builds may trigger OS security warnings. Obtain trusted publisher-signed builds.\n",
            encoding="utf-8",
        )
        (stage / "build-info.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
        archive_format = "zip" if plan.target == "windows" else "gztar"
        archive = Path(shutil.make_archive(
            str(release_dir / basename), archive_format, root_dir=temp, base_dir=APP_NAME,
        ))
    metadata_path = release_dir / f"{basename}.json"
    metadata_path.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    (release_dir / f"{basename}.sha256").write_text(
        f"{sha256_file(archive)}  {archive.name}\n"
        f"{sha256_file(metadata_path)}  {metadata_path.name}\n", encoding="ascii",
    )
    return archive


def main(argv: list[str] | None = None) -> int:
    options_path = SOURCE_DIR / "build_options.json"
    try:
        options = json.loads(options_path.read_text(encoding="utf-8")) if options_path.exists() else {}
        if not isinstance(options, dict) or not isinstance(options.get("platform_modes", {}), dict):
            raise ValueError("build_options.json must be an object with an optional platform_modes object.")
        parser = argparse.ArgumentParser(description=__doc__)
        parser.add_argument("--target", choices=["windows", "macos", "linux"], help="Must match the build host OS.")
        default_mode = options.get("platform_modes", {}).get(TARGETS.get(platform.system()), options.get("mode", "onedir"))
        parser.add_argument("--mode", choices=["onedir", "onefile"], default=default_mode)
        parser.add_argument("--version", default=options.get("version", "1.0.0"))
        parser.add_argument("--entry", type=Path, default=SOURCE_DIR / "sensor_desktop_app.py")
        parser.add_argument("--output", type=Path, default=SOURCE_DIR / "dist" / "native")
        parser.add_argument("--calibrations", type=Path, help="Bake a saved calibration JSON profile into the app.")
        parser.add_argument("--codesign-identity", help="macOS Developer ID identity already installed in your keychain.")
        parser.add_argument("--skip-smoke-test", action="store_true", help="Skip GUI validation; not recommended for distribution.")
        parser.add_argument("--dry-run", action="store_true", help="Show the build plan without installing or building anything.")
        args = parser.parse_args(argv)
        snapshot: AppSnapshot | None = None
        if not args.dry_run:
            source_entry = args.entry.resolve()
            if not source_entry.is_file():
                raise ValueError(f"Python application entry point not found: {source_entry}")
            snapshot = stage_app_snapshot(source_entry, SOURCE_DIR / ".build" / "app-snapshot")
            print(
                f"Staged {len(snapshot.copied)} application file(s) from {snapshot.source_dir.name}/ "
                "into a neutral build folder so imports do not depend on your repository layout.",
                flush=True,
            )
            for location in snapshot.normalized:
                print(f"  normalized local import at {location}", flush=True)
            plan = create_build_plan(snapshot.entry, args.output, args.target, args.mode, args.version)
        else:
            plan = create_build_plan(args.entry, args.output, args.target, args.mode, args.version)
        if args.codesign_identity and plan.target != "macos":
            raise ValueError("--codesign-identity is only supported on macOS.")
        if args.dry_run:
            print(json.dumps({
                "target": plan.target, "architecture": plan.architecture, "mode": plan.mode,
                "entry": str(plan.entry), "application": str(plan.app_path),
                "executable": str(plan.executable_path), "releases": str(plan.output_dir / "releases"),
                "requires_native_host": True,
            }, indent=2))
            return 0
        assert snapshot is not None
        extra_hiddenimports: List[str] = []
        extra_paths: List[Path] = []
        if snapshot.unresolved:
            print(
                "WARNING: these imports could not be rewritten to top-level form and will be "
                "bundled through the source package instead:",
                flush=True,
            )
            for location in snapshot.unresolved:
                print(f"  {location}", flush=True)
            extra_hiddenimports.append(snapshot.source_package)
            extra_paths.append(snapshot.source_dir.parent)
        check_dependencies()
        plan.work_dir.mkdir(parents=True, exist_ok=True)
        plan.output_dir.mkdir(parents=True, exist_ok=True)
        source_profile = args.calibrations
        if source_profile is None and (SOURCE_DIR / "default_calibrations.json").exists():
            source_profile = SOURCE_DIR / "default_calibrations.json"
        profile = stage_calibrations(source_profile, plan.work_dir)
        spec = plan.work_dir / f"{APP_NAME}.spec"
        spec.write_text(
            render_spec(plan, profile, args.codesign_identity, extra_hiddenimports, extra_paths),
            encoding="utf-8",
        )
        command = [
            sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
            "--distpath", str(plan.output_dir / "app"),
            "--workpath", str(plan.work_dir / "work"), str(spec),
        ]
        print(f"Building {plan.target} / {plan.architecture} / {plan.mode}", flush=True)
        print(shlex.join(command), flush=True)
        subprocess.run(command, check=True, cwd=SOURCE_DIR)
        if args.skip_smoke_test:
            print("WARNING: GUI smoke test skipped. Validate on a clean target machine before sharing.", flush=True)
        else:
            smoke_test(plan)
        archive = create_release(plan, tested=not args.skip_smoke_test)
        print(f"\nApplication: {plan.app_path}\nShareable archive: {archive}\nChecksums and build metadata: {archive.parent}", flush=True)
        print("End users do not need Python. Windows/macOS public distribution also needs publisher signing.", flush=True)
        return 0
    except (ValueError, OSError, RuntimeError, subprocess.SubprocessError) as exc:
        print(f"Build failed: {exc}", file=sys.stderr, flush=True)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())